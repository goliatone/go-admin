func TestLegacyExportAdoptionReplayRetainedPublication(t *testing.T) {
	for _, fault := range []string{"targets", "operation", "publication_marker", "plan_owner", "plan_namespace", "plan_digest"} {
		t.Run(fault, func(t *testing.T) {
			f := newLegacyFixture(t)
			f.record("queued", export.StateQueued)
			request := f.review("queued")
			f.apply(request)
			message, receipt, err := f.h.Queue.Dequeue(context.Background())
			adoptionRecoveryMust(t, err)
			adoptionRecoveryMust(t, f.h.ExecuteMessage(context.Background(), message))
			adoptionRecoveryMust(t, f.h.Queue.Ack(context.Background(), receipt))
			f.apply(request) // Healthy completed replay must remain supported.
			queries := map[string]string{
				"targets":            "DELETE FROM export_webhook_targets",
				"operation":          "DELETE FROM export_webhook_operations",
				"publication_marker": "UPDATE export_webhook_completion_plans SET published_at=NULL",
				"plan_owner":         "UPDATE export_webhook_completion_plans SET owner='other'",
				"plan_namespace":     "UPDATE export_webhook_completion_plans SET namespace='other'",
				"plan_digest":        "UPDATE export_webhook_completion_plans SET digest='corrupt'",
			}
			adoptionRecoveryExec(t, f.db, queries[fault])
			before, err := adoptionRecoveryState(f.db)
			adoptionRecoveryMust(t, err)
			result, err := f.h.AdoptLegacyExport(context.Background(), f.actor, request)
			if err == nil || !reflect.DeepEqual(result, LegacyExportAdoptionResult{}) {
				t.Fatalf("incomplete retained publication acknowledged: %+v %v", result, err)
			}
			inventoryUnchanged(t, f, before)
			if f.accepts.Load() != 1 || f.sourceCalls.Load() != 1 {
				t.Fatal("replay renewed authority or regenerated bytes")
			}
		})
	}
}

func TestLegacyExportAdoptionRequestNumericFidelity(t *testing.T) {
	for _, test := range []struct {
		name, number string
		safe         bool
	}{
		{"large_integer", "9007199254740993", false},
		{"fraction", "1.0000000000000001", false},
		{"underflow", "1e-400", false},
		{"scientific_loss", "9.007199254740993e15", false},
		{"integer", "9007199254740992", true},
		{"decimal", "0.1", true},
		{"equivalent_decimal", "1.0", true},
		{"equivalent_exponent", "1e0", true},
		{"zero_extreme_exponent", "0e-99999999999", true},
	} {
		t.Run(test.name, func(t *testing.T) {
			for _, location := range []string{"query", "selection", "template"} {
				t.Run(location, func(t *testing.T) {
					f := inventoryFixture(t)
					f.record("queued", export.StateQueued)
					var raw []byte
					adoptionRecoveryMust(t, f.db.NewSelect().Table("export_records").Column("request_payload").Scan(context.Background(), &raw))
					var request export.ExportRequest
					decoder := json.NewDecoder(bytes.NewReader(raw))
					decoder.UseNumber()
					adoptionRecoveryMust(t, decoder.Decode(&request))
					value := map[string]any{"nested": []any{json.Number(test.number)}}
					switch location {
					case "query":
						request.Query = value
					case "selection":
						request.Selection.Query.Params = value
					case "template":
						request.RenderOptions.Template.Data = value
					}
					request.EstimatedBytes = 9007199254740993 // Typed integers must remain valid.
					raw, err := json.Marshal(request)
					adoptionRecoveryMust(t, err)
					adoptionRecoveryExec(t, f.db, "UPDATE export_records SET request_payload=?", raw)
					before, err := adoptionRecoveryState(f.db)
					adoptionRecoveryMust(t, err)
					review, reviewErr := f.h.PreviewLegacyExport(context.Background(), f.actor, "queued", "profile-v2")
					page, pageErr := f.h.InventoryLegacyExports(context.Background(), f.actor, inventoryQuery())
					if test.safe {
						adoptionRecoveryMust(t, reviewErr)
						adoptionRecoveryMust(t, pageErr)
						if len(page.Entries) != 1 || page.Entries[0].Review == nil {
							t.Fatal("safe request omitted", page)
						}
						inventoryUnchanged(t, f, before)
						f.apply(LegacyExportAdoptionRequest{ExportID: review.ExportID, ProfileRef: review.ProfileRef, RecordSHA256: review.RecordSHA256, PlanSHA256: review.PlanSHA256})
					} else {
						if reviewErr == nil || !reflect.DeepEqual(review, LegacyExportReview{}) {
							t.Error("lossy request preview acknowledged", reviewErr)
						}
						if pageErr == nil || !reflect.DeepEqual(page, LegacyExportInventoryResult{}) {
							t.Error("lossy request inventory acknowledged", pageErr)
						}
						// Even a well-shaped request cannot bypass service validation.
						applyRequest := LegacyExportAdoptionRequest{ExportID: "queued", ProfileRef: "profile-v2", RecordSHA256: "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa", PlanSHA256: "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb"}
						if reviewErr == nil {
							applyRequest.RecordSHA256, applyRequest.PlanSHA256 = review.RecordSHA256, review.PlanSHA256
						}
						_, applyErr := f.h.AdoptLegacyExport(context.Background(), f.actor, applyRequest)
						if applyErr == nil {
							t.Error("lossy request applied")
						}
						inventoryUnchanged(t, f, before)
						f.noAdoption()
					}
				})
			}
		})
	}
}

func TestLegacyExportAdoptionQueuedReplayDrift(t *testing.T) {
	for _, fault := range []string{"request", "premature_publication"} {
		t.Run(fault, func(t *testing.T) {
			f := newLegacyFixture(t)
			f.record("queued", export.StateQueued)
			reviewed := f.review("queued")
			f.apply(reviewed)
			if fault == "request" {
				record, err := f.h.Tracker.Status(context.Background(), "queued")
				adoptionRecoveryMust(t, err)
				record.Request.Query = map[string]any{"changed": "after-review"}
				raw, err := json.Marshal(record.Request)
				adoptionRecoveryMust(t, err)
				adoptionRecoveryExec(t, f.db, "UPDATE export_records SET request_payload=?", raw)
			} else {
				adoptionRecoveryExec(t, f.db, "UPDATE export_webhook_completion_plans SET published_at=?", f.h.cfg.Now())
			}
			before, err := adoptionRecoveryState(f.db)
			adoptionRecoveryMust(t, err)
			result, err := f.h.AdoptLegacyExport(context.Background(), f.actor, reviewed)
			if err == nil || !reflect.DeepEqual(result, LegacyExportAdoptionResult{}) {
				t.Fatalf("queued replay accepted changed retained state: %+v %v", result, err)
			}
			inventoryUnchanged(t, f, before)
			if f.accepts.Load() != 1 || f.sourceCalls.Load() != 0 {
				t.Fatal("replay repeated work")
			}
		})
	}
}
